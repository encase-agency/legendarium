import type { ReactNode } from 'react'

export interface Crop {
  w: number
  h: number
  left: number
  top: number
}

export interface Poster {
  src: string
  crop?: Crop
  /** Black backdrop behind a letterboxed crop (Telegram, copywriting in the file). */
  black?: boolean
}

export type Line = string | { text: string; size?: 15; bold?: boolean; gray?: boolean; w?: number }

// Modal copy comes 1:1 from the Figma frames (421:1388 ... 424:1809), typos included.
export type Block =
  | { t: 'qa'; label: string; strong?: string; lines?: Line[]; bullets?: string[] }
  | { t: 'text'; lines: Line[] }
  | { t: 'list'; title: string; items: (string | string[])[] }

export interface Course {
  id: string
  poster: Poster
  card: { title: ReactNode; titleWeight?: number; body: ReactNode }
  modal: {
    title: string[]
    blocks: Block[]
    mentor: { name: string; role: string[] }
  }
}

const Dim = ({ children, tone = '#7f7f7f' }: { children: ReactNode; tone?: string }) => (
  <span style={{ color: tone }}>{children}</span>
)
const Hi = ({ children, weight }: { children: ReactNode; weight?: number }) => (
  <span className="fc-hi" style={weight ? { fontWeight: weight } : undefined}>
    {children}
  </span>
)

